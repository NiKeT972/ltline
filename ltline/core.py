"""Shared data, feature and model logic for LTLine.

The raw dataset (data/lt_faults_augmented.csv) holds five contiguous blocks of
2,000 time-ordered readings: Healthy, Break, Arc, Overload, Short Circuit.
Each fault block was generated by injecting a fault into a copy of the same
healthy waveform, but parts of the Break and Arc blocks were left untouched
while still carrying the fault label (1,000 and 1,700 rows respectively).
`load_segments` removes those mislabeled rows so every label matches its signal.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA_PATH = ROOT / "data" / "lt_faults_augmented.csv"
MODELS_DIR = ROOT / "models"

CLASSES = ["Healthy", "Break", "Arc", "Overload", "Short Circuit"]
FAULTS = CLASSES[1:]
BLOCK = 2000
WINDOW = 5  # samples in the rolling window
PERSIST_TO_CONFIRM = 3   # consecutive anomalous samples before a trip is allowed
AGREE_TO_CONFIRM = 3     # consecutive identical, confident fault predictions


SAFE_CURRENT_MAX = 12.5          # A, rated feeder current at the dataset's scale
SAFE_VOLT_MIN, SAFE_VOLT_MAX = 207.0, 253.0  # V, for a 230 V system

FEATURES = [
    "current", "voltage",
    "current_std", "voltage_std",
    "current_dabs", "voltage_dabs",
]


def load_segments(path: Path = DATA_PATH) -> dict[str, pd.DataFrame]:
    """Return one cleaned, time-ordered DataFrame per class."""
    df = pd.read_csv(path).dropna(subset=["current", "voltage", "label"])
    base = df.iloc[:BLOCK][["current", "voltage"]].to_numpy()
    segments: dict[str, pd.DataFrame] = {}
    for k, label in enumerate(CLASSES):
        seg = df.iloc[BLOCK * k: BLOCK * (k + 1)].reset_index(drop=True)
        assert (seg["label"] == label).all(), f"Unexpected block order at {label}"
        if label != "Healthy":
            vals = seg[["current", "voltage"]].to_numpy()
            untouched = np.all(np.isclose(vals, base[: len(vals)]), axis=1)
            seg = seg[~untouched].reset_index(drop=True)
        segments[label] = seg[["current", "voltage", "label"]]
    return segments


def make_features(signal: pd.DataFrame) -> pd.DataFrame:
    """Point readings plus rolling-window shape features (jaggedness, spread)."""
    f = pd.DataFrame({"current": signal["current"].to_numpy(),
                      "voltage": signal["voltage"].to_numpy()})
    for c in ("current", "voltage"):
        f[f"{c}_std"] = f[c].rolling(WINDOW, min_periods=1).std().fillna(0.0)
        f[f"{c}_dabs"] = f[c].diff().abs().rolling(WINDOW, min_periods=1).mean().fillna(0.0)
    return f[FEATURES]


def load_models():
    from joblib import load
    iso = load(MODELS_DIR / "isoforest.joblib")
    rf = load(MODELS_DIR / "fault_rf.joblib")
    meta = json.loads((MODELS_DIR / "meta.json").read_text())
    return iso, rf, meta


def models_exist() -> bool:
    return all((MODELS_DIR / n).exists()
               for n in ("isoforest.joblib", "fault_rf.joblib", "meta.json"))


def simulate_trip(stream: pd.DataFrame, iso, rf, threshold: float, conf_thresh: float = 0.8):
    """Run the full detect -> confirm -> trip logic over a stream.

    Returns (sample_index, fault) at the moment the line trips, or None.
    Mirrors the logic in app.py, vectorised for evaluation.
    """
    X = make_features(stream)[FEATURES]
    scores = -iso.decision_function(X)
    proba = rf.predict_proba(X)
    classes = list(rf.classes_)
    persist, recent, warning = 0, [], False
    for i in range(len(stream)):
        anomalous = i >= WINDOW - 1 and scores[i] > threshold
        persist = persist + 1 if anomalous else 0
        k = int(proba[i].argmax())
        pred, conf = classes[k], float(proba[i][k])
        recent = (recent + [pred])[-AGREE_TO_CONFIRM:]
        if anomalous:
            warning = True
        elif persist == 0:
            warning = False
        if (warning and persist >= PERSIST_TO_CONFIRM and pred != "Healthy" and conf >= conf_thresh
                and len(recent) == AGREE_TO_CONFIRM and len(set(recent)) == 1):
            return i, pred
    return None
